// Generates functions/lib/assistant-catalog.js from js/catalog.js: for each product, the words a customer might use for it and the product
// page that really exists. The shopping-assistant endpoint (/api/assistant/offer) matches on these and links to these pages, so a URL is never
// made up: a product without a page gets `page: null`. Run: node scripts/build-assistant-catalog.js   (a test fails if the file is stale)
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');

function build() {
  const win = {}; vm.runInNewContext(fs.readFileSync(path.join(root, 'js/catalog.js'), 'utf8'), { window: win });
  const out = {};
  for (const p of win.NTAGZ_CATALOG.products) {
    const page = p.detail && fs.existsSync(path.join(root, p.detail, 'index.html')) ? '/' + p.detail.replace(/^\/+/, '') : null;
    out[p.id] = { sku: p.sku, name: p.name, page, keywords: [...new Set([p.sku, p.homeCategory, p.category, ...(p.tags || [])].filter(Boolean).map(String))] };
  }
  return `// GENERATED by scripts/build-assistant-catalog.js from js/catalog.js. Do not edit by hand.\nmodule.exports = ${JSON.stringify(out, null, 2)};\n`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(root, 'functions/lib/assistant-catalog.js'), build());
  console.log('functions/lib/assistant-catalog.js written');
}
module.exports = { build };
